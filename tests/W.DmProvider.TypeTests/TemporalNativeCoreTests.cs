using System.Globalization;
using W.Dm.Internal.Types;
using Xunit;

namespace W.DmProvider.TypeTests;

public sealed class TemporalNativeCoreTests
{
    private static DmTemporalFields Seed(int ns = 100, int? offset = null) => new(2026, 7, 23, 14, 15, 16, ns, offset);

    [Theory]
    [InlineData(null, "EA87BBEE81C8000000")]
    [InlineData(0, "EA87BBEE81C80000000000")]
    [InlineData(480, "EA87BBEE81C8000000E001")]
    [InlineData(-300, "EA87BBEE81C8000000D4FE")]
    [InlineData(330, "EA87BBEE81C80000004A01")]
    public void OfficialGoldensRetainLocalTickAndOriginalOffset(int? offset, string hex)
    {
        // Frozen official goldens from ExtendedTemporalPrecisionTests, not generated by this codec.
        var layout = offset.HasValue ? DmTemporalWireLayout.TimestampTz11 : DmTemporalWireLayout.Timestamp9;
        byte[] golden = Convert.FromHexString(hex);
        Assert.Equal(golden, DmTemporalWireCodec.EncodeExact(Seed(offset: offset), layout, 7));
        var raw = DmTemporalWireCodec.DecodeRaw(golden, layout, 7);
        Assert.Equal(Seed(offset: offset), raw);
        long expected = new DateTime(2026, 7, 23, 14, 15, 16).Ticks + 1;
        Assert.Equal(expected, DmTemporalInteger.ProjectDateTime(raw).Ticks);
        if (offset.HasValue)
        {
            var projected = DmTemporalInteger.ProjectDateTimeOffset(raw);
            Assert.Equal(expected, projected.Ticks);
            Assert.Equal(offset.Value * TimeSpan.TicksPerMinute, projected.Offset.Ticks);
        }
    }

    [Theory]
    [InlineData(999999900, 0, "0F27FE77DF39933577")]
    [InlineData(999999800, 1, "0F27FE77DF71923577")]
    [InlineData(999999000, 9, "0F27FE77DF318C3577")]
    public void ManuallyPackedMaximumDateVectorsAreExact(int ns, int ticksBelowMax, string hex)
    {
        // Date bits: 9999=0x270F, month=12/day=31 => FE; 23:59:59 => 77 DF + low second bit.
        // Fraction bytes are the independent integer shifts of the stated ns, not encoder output.
        var fields = new DmTemporalFields(9999, 12, 31, 23, 59, 59, ns);
        Assert.Equal(Convert.FromHexString(hex), DmTemporalWireCodec.EncodeExact(fields, DmTemporalWireLayout.Timestamp9, 7));
        Assert.Equal(fields, DmTemporalWireCodec.DecodeRaw(Convert.FromHexString(hex), DmTemporalWireLayout.Timestamp9, 7));
        Assert.Equal(DateTime.MaxValue.Ticks - ticksBelowMax, DmTemporalInteger.ProjectDateTime(fields).Ticks);
        if (ns % 1000 != 0)
            Assert.Throws<OverflowException>(() => DmTemporalWireCodec.EncodeExact(fields, DmTemporalWireLayout.Timestamp8, 6));
        else
            Assert.Equal("9999-12-31 23:59:59.999999", DmTemporalInteger.FormatExact(fields, 6, DmTemporalTextKind.Timestamp));
    }

    [Theory]
    [InlineData(0)] [InlineData(1)] [InlineData(2)] [InlineData(3)] [InlineData(4)]
    [InlineData(5)] [InlineData(6)] [InlineData(7)] [InlineData(8)] [InlineData(9)]
    public void EveryScaleRequiresItsExactIntegerQuantum(int scale)
    {
        int quantum = DmTemporalInteger.PowerOfTen(9 - scale);
        int ns = scale == 0 ? 0 : quantum;
        DmTemporalInteger.ValidateWireFraction(ns, scale);
        string suffix = scale == 0 ? "" : "." + new string('0', scale - 1) + "1";
        Assert.Equal("2026-07-23 14:15:16" + suffix, DmTemporalInteger.FormatExact(Seed(ns), scale, DmTemporalTextKind.Timestamp));
        if (scale < 9) Assert.Throws<OverflowException>(() => DmTemporalInteger.ValidateWireFraction(ns + 1, scale));
        if (scale <= 7) Assert.Equal(ns / 100, DmTemporalInteger.FractionalTicksExact(ns));
        else Assert.Throws<OverflowException>(() => DmTemporalInteger.FractionalTicksExact(ns));
    }

    [Theory]
    [InlineData(8, 10, "00000001", false)] [InlineData(8, 90, "00000009", false)]
    [InlineData(8, 100, "00000010", true)] [InlineData(9, 1, "000000001", false)]
    [InlineData(9, 99, "000000099", false)] [InlineData(9, 100, "000000100", true)]
    public void ValidSubTickFieldsKeepTextAndRejectOnlyClrProjection(int scale, int ns, string fraction, bool clr)
    {
        var fields = Seed(ns);
        byte[] wire = DmTemporalWireCodec.EncodeExact(fields, DmTemporalWireLayout.Timestamp9, scale);
        Assert.Equal(fields, DmTemporalWireCodec.DecodeRaw(wire, DmTemporalWireLayout.Timestamp9, scale));
        Assert.Equal("2026-07-23 14:15:16." + fraction, DmTemporalInteger.FormatExact(fields, scale, DmTemporalTextKind.Timestamp));
        if (clr) Assert.Equal(new DateTime(2026, 7, 23, 14, 15, 16).Ticks + 1, DmTemporalInteger.ProjectDateTime(fields).Ticks);
        else Assert.Throws<OverflowException>(() => DmTemporalInteger.ProjectDateTime(fields));
        Assert.Throws<OverflowException>(() => DmTemporalWireCodec.ToLegacyMicroseconds(fields, DmTemporalTextKind.Timestamp));
    }

    [Fact]
    public void WirePrecisionMetadataCannotBeMaskedAsUserScale()
    {
        foreach (int scale in new[] { -1, 19, 23, 255, 0x1006 })
        {
            Assert.Throws<ArgumentOutOfRangeException>(() => DmTemporalInteger.ValidateUserScale(scale));
            Assert.Throws<OverflowException>(() => DmTemporalInteger.ValidateWireFraction(0, scale));
        }
        foreach (int precision in new[] { -1, 7, 9, 255 })
            Assert.Throws<NotSupportedException>(() => DmTemporalInteger.ValidateUserPrecision(precision));
        DmTemporalInteger.ValidateUserPrecision(0);
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ValidateWireFraction(1, 8));
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ValidateWireFraction(-1, 9));
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ValidateWireFraction(1_000_000_000, 9));
    }

    [Fact]
    public void RawMetadataIsSeparateFromEffectiveScaleAndMask()
    {
        var raw = new DmTemporalRawMetadata(DmTemporalMetadataSource.ResultColumn, 26, 9, 0x1006, 3, 0, 4,
            DmTemporalResultFormat.OrdinaryPacked);
        Assert.True(raw.HasServerSource);
        var changed = raw with { Scale = 7, DerivedMask = 0 };
        Assert.Equal(0x1006, raw.Scale);
        Assert.Equal(4, raw.DerivedMask);
        Assert.Equal(7, changed.Scale);
        Assert.False((raw with { Source = DmTemporalMetadataSource.Synthetic }).HasServerSource);
    }

    [Theory]
    [InlineData(DateTimeKind.Unspecified)] [InlineData(DateTimeKind.Local)] [InlineData(DateTimeKind.Utc)]
    public void KindNeverChangesWallClockEncoding(DateTimeKind kind)
    {
        DateTime date = new DateTime(2026, 7, 23, 14, 15, 16, kind).AddTicks(1);
        Assert.Equal(Seed(), DmTemporalInteger.FromDateTime(date));
        Assert.Equal(DateTimeKind.Unspecified, DmTemporalInteger.ProjectDateTime(Seed()).Kind);
    }

    [Fact]
    public void MinDatesLeapCenturiesAndGregorianGapAreNotRewritten()
    {
        Assert.Equal(0, DmTemporalInteger.ProjectDateTime(new(1, 1, 1, 0, 0, 0, 0)).Ticks);
        Assert.Equal(1, DmTemporalInteger.ProjectDateTime(new(1, 1, 1, 0, 0, 0, 100)).Ticks);
        Assert.Equal(DateOnly.MinValue, DmTemporalInteger.ProjectDateOnly(DmTemporalInteger.FromDateOnly(DateOnly.MinValue)));
        Assert.Equal(DateOnly.MaxValue, DmTemporalInteger.ProjectDateOnly(DmTemporalInteger.FromDateOnly(DateOnly.MaxValue)));
        foreach (int year in new[] { 2000, 2400 }) DmTemporalInteger.ValidateDate(new(year, 2, 29, 0, 0, 0, 0));
        foreach (int year in new[] { 1900, 2100 }) Assert.Throws<OverflowException>(() => DmTemporalInteger.ValidateDate(new(year, 2, 29, 0, 0, 0, 0)));
        for (int day = 5; day <= 14; day++)
        {
            var raw = new DmTemporalFields(1582, 10, day, 0, 0, 0, 0);
            Assert.Equal(day, DmTemporalWireCodec.DecodeRaw(DmTemporalWireCodec.EncodeExact(raw, DmTemporalWireLayout.Date3, 0), DmTemporalWireLayout.Date3, 0).Day);
        }
        var bce = new DmTemporalFields(-4712, 1, 1, 0, 0, 0, 0);
        Assert.Equal("-4712-01-01", DmTemporalInteger.FormatExact(bce, 0, DmTemporalTextKind.Date));
        Assert.Equal(bce, DmTemporalWireCodec.DecodeRaw(DmTemporalWireCodec.EncodeExact(bce, DmTemporalWireLayout.Date3, 0), DmTemporalWireLayout.Date3, 0));
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ProjectDateTime(bce));
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ProjectDateTime(new(10000, 1, 1, 0, 0, 0, 0)));
    }

    [Fact]
    public void EveryFinalTickDigitIsKeptOrStrictlyRejectedAtSixDigits()
    {
        for (int tail = 0; tail <= 9; tail++)
        {
            var minimum = new DmTemporalFields(1, 1, 1, 0, 0, 0, tail * 100);
            var maximum = new DmTemporalFields(9999, 12, 31, 23, 59, 59, 999999000 + tail * 100);
            Assert.Equal((long)tail, DmTemporalInteger.ProjectDateTime(minimum).Ticks);
            Assert.Equal(DateTime.MaxValue.Ticks - 9 + tail, DmTemporalInteger.ProjectDateTime(maximum).Ticks);
            if (tail == 0)
            {
                DmTemporalInteger.ValidateWireFraction(minimum.NanosecondsWithinSecond, 6);
                DmTemporalInteger.ValidateWireFraction(maximum.NanosecondsWithinSecond, 6);
            }
            else
            {
                Assert.Throws<OverflowException>(() => DmTemporalInteger.ValidateWireFraction(minimum.NanosecondsWithinSecond, 6));
                Assert.Throws<OverflowException>(() => DmTemporalInteger.ValidateWireFraction(maximum.NanosecondsWithinSecond, 6));
            }
        }
    }

    [Theory]
    [InlineData(-840)] [InlineData(-780)] [InlineData(-779)] [InlineData(0)] [InlineData(840)]
    public void PureClrOffsetRangeDoesNotPromiseServerAcceptance(int minutes)
    {
        var fields = Seed(offset: minutes);
        Assert.Equal(minutes * TimeSpan.TicksPerMinute, DmTemporalInteger.ProjectDateTimeOffset(fields).Offset.Ticks);
        Assert.Equal(fields, DmTemporalInteger.FromDateTimeOffset(DmTemporalInteger.ProjectDateTimeOffset(fields)));
    }

    [Fact]
    public void OffsetProjectionChecksLocalAndUtcIndependently()
    {
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ProjectDateTimeOffset(new(1, 1, 1, 0, 0, 0, 0, 1)));
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ProjectDateTimeOffset(new(9999, 12, 31, 23, 59, 59, 999999900, -1)));
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ProjectDateTimeOffset(Seed(offset: 841)));
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ProjectDateTimeOffset(Seed(offset: -841)));
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ProjectDateTimeOffset(new(10000, 1, 1, 0, 0, 0, 0, 0)));
        Assert.Throws<InvalidCastException>(() => DmTemporalInteger.ProjectDateTimeOffset(Seed()));
        Assert.Equal(0, DmTemporalInteger.ProjectDateTimeOffset(new(1, 1, 1, 0, 1, 0, 0, 1)).UtcTicks);
        Assert.Equal(DateTime.MaxValue.Ticks, DmTemporalInteger.ProjectDateTimeOffset(new(9999, 12, 31, 23, 58, 59, 999999900, -1)).UtcTicks);
    }

    [Fact]
    public void TimeMidnightAndLastTickDoNotWrapHour24()
    {
        Assert.Equal(TimeOnly.MinValue, DmTemporalInteger.ProjectTimeOnly(DmTemporalInteger.FromTimeOnly(TimeOnly.MinValue)));
        Assert.Equal(TimeOnly.MaxValue, DmTemporalInteger.ProjectTimeOnly(DmTemporalInteger.FromTimeOnly(TimeOnly.MaxValue)));
        var end = new DmTemporalFields(0, 0, 0, 24, 0, 0, 0);
        Assert.Equal("24:00:00", DmTemporalInteger.FormatExact(end, 0, DmTemporalTextKind.Time));
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ProjectTimeOnly(end));
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ProjectTimeSpanExact(end));
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ProjectTimeDateTime(end));
        Assert.Throws<OverflowException>(() => DmTemporalInteger.ValidateTime(end with { Second = 1 }));
        Assert.Equal(new DateTime(1900, 1, 1, 14, 15, 16).Ticks + 1,
            DmTemporalInteger.ProjectTimeDateTime(new(0, 0, 0, 14, 15, 16, 100)).Ticks);
    }

    [Fact]
    public void FormattingIsInvariantAndKeepsDeclaredZerosAndOffset()
    {
        CultureInfo old = CultureInfo.CurrentCulture;
        try
        {
            foreach (string culture in new[] { "", "zh-CN", "en-US", "fr-FR", "ar-SA" })
            {
                CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo(culture);
                Assert.Equal("2026-07-23 14:15:16.123456000 -05:00",
                    DmTemporalInteger.FormatExact(Seed(123456000, -300), 9, DmTemporalTextKind.Timestamp));
            }
        }
        finally { CultureInfo.CurrentCulture = old; }
    }
}
